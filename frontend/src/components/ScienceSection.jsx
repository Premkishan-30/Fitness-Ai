import { useRef, useEffect } from 'react';
import { 
  ShieldCheck, 
  Award, 
  Microscope, 
  Lock
} from 'lucide-react';
import gsap from 'gsap';
import { ScrollTrigger } from 'gsap/ScrollTrigger';
import { resetPointerTilt, tiltOnPointerMove } from '../utils/tiltMotion';

gsap.registerPlugin(ScrollTrigger);

export default function ScienceSection() {
  const sectionRef = useRef(null);

  useEffect(() => {
    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if (prefersReducedMotion) return;

    const ctx = gsap.context(() => {
      const timeline = gsap.timeline({
        scrollTrigger: { trigger: sectionRef.current, start: 'top 80%' },
      });
      timeline.fromTo('.science-stat-card',
        { clipPath: 'inset(0 0 100% 0 round 18px)', y: 24, rotateX: 8, opacity: 0 },
        { clipPath: 'inset(0 0 0% 0 round 18px)', y: 0, rotateX: 0, opacity: 1, duration: 0.72, stagger: 0.13, ease: 'power3.out' }
      );
      timeline.fromTo('.science-pillar-card',
        { x: -22, opacity: 0, scale: 0.97 },
        { x: 0, opacity: 1, scale: 1, duration: 0.58, stagger: 0.14, ease: 'power2.out' },
        '-=0.16'
      );

      gsap.utils.toArray('.science-stat-value').forEach((element) => {
        const match = element.textContent.trim().match(/^([^\d]*)([\d,]+(?:\.\d+)?)(.*)$/);
        if (!match) return;
        const target = Number(match[2].replace(/,/g, ''));
        const count = { value: 0 };
        gsap.fromTo(count, { value: 0 }, {
          value: target,
          duration: 1.05,
          ease: 'power2.out',
          scrollTrigger: { trigger: element, start: 'top 86%' },
          onUpdate: () => {
            const value = Number.isInteger(target) ? Math.round(count.value).toLocaleString('en-US') : count.value.toFixed(1);
            element.textContent = `${match[1]}${value}${match[3]}`;
          },
        });
      });
    }, sectionRef);

    return () => ctx.revert();
  }, []);

  const stats = [
    {
      value: '480k+',
      label: 'Biological Data Points',
      desc: 'Processed monthly per user across raw photoplethysmography (PPG), ECG, and interstitial glucose.',
    },
    {
      value: '3.2x',
      label: 'Faster Overtraining Detection',
      desc: 'Autonomic nervous system (ANS) decompensation identified days before physical fatigue manifests.',
    },
    {
      value: '94%',
      label: 'Reported Sleep Improvement',
      desc: 'Users reported measurable increases in deep sleep duration and subjective morning vigor within 30 days.',
    },
    {
      value: '0.81',
      label: 'Average Pace of Aging',
      desc: 'Active users demonstrated a reduction in phenotypic biological aging rate (0.81 biological yr / calendar yr).',
    },
  ];

  const pillars = [
    {
      title: 'Autonomic HRV Spectral Analysis',
      body: 'We utilize root mean square of successive differences (rMSSD) sampled at sub-second intervals to calculate the delicate equilibrium between parasympathetic recovery and sympathetic stress.',
      tag: 'CARDIAC RESILIENCE',
    },
    {
      title: 'Circadian Phase & Thermal Shifting',
      body: 'Continuous distal skin temperature monitoring enables precise detection of core circadian phase delays, allowing the AI to optimize sleep timing and evening nutrition windows.',
      tag: 'CHRONOBIOLOGY',
    },
    {
      title: 'Longitudinal Phenotypic Decay Models',
      body: 'Our predictive algorithms cross-reference annual comprehensive lipid panels (ApoB, hs-CRP, fasting insulin) with everyday strain to estimate organ resilience and longevity trajectories.',
      tag: 'LONGEVITY SCIENCE',
    },
  ];

  return (
    <section
      ref={sectionRef}
      className="py-20 md:py-32 relative overflow-hidden bg-slate-50/70 border-t border-slate-200"
    >
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 relative z-10">
        {/* Header */}
        <div className="text-center max-w-3xl mx-auto mb-16">
          <div className="inline-flex items-center gap-2 px-3.5 py-1 rounded-full bg-blue-50 border border-blue-200 text-blue-700 text-xs font-bold uppercase tracking-wider mb-4">
            <Microscope className="w-3.5 h-3.5" />
            <span>RIGOROUS PHYSIOLOGICAL SCIENCE</span>
          </div>
          <h2 className="text-3xl sm:text-5xl font-extrabold text-slate-900 tracking-tight">
            Built on peer-reviewed biology,{' '}
            <span className="text-blue-600">not algorithmic fads</span>
          </h2>
          <p className="text-base sm:text-lg text-slate-600 mt-4 leading-relaxed font-normal">
            Every score, curve, and recommendation generated by Fitness is rooted in
            validated cardiovascular physiology, chronobiology, and metabolic endocrinology.
          </p>
        </div>

        {/* 4 Stats Grid */}
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-6 mb-16">
          {stats.map((stat, idx) => (
            <div
              key={idx}
              onPointerMove={tiltOnPointerMove}
              onPointerLeave={resetPointerTilt}
              className="science-stat-card p-6 rounded-2xl bg-white border border-slate-200 shadow-sm hover:border-blue-400 hover:shadow-md transition-all duration-300"
            >
              <div className="science-stat-value text-4xl sm:text-5xl font-black text-blue-600 font-mono tracking-tight mb-2">
                {stat.value}
              </div>
              <h3 className="text-sm font-bold text-slate-900 mb-2">{stat.label}</h3>
              <p className="text-xs text-slate-500 leading-relaxed font-normal">{stat.desc}</p>
            </div>
          ))}
        </div>

        {/* 3 Scientific Foundations Pillars */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
          {pillars.map((pillar, idx) => (
            <div
              key={idx}
              onPointerMove={tiltOnPointerMove}
              onPointerLeave={resetPointerTilt}
              className="science-pillar-card p-6 rounded-2xl bg-white border border-slate-200 shadow-sm hover:border-blue-400 hover:shadow-md transition-all duration-300"
            >
              <span className="text-[10px] font-mono font-bold text-blue-700 bg-blue-50 border border-blue-200 px-2 py-0.5 rounded-full uppercase tracking-wider mb-3 inline-block">
                {pillar.tag}
              </span>
              <h3 className="text-lg font-bold text-slate-900 mb-2">{pillar.title}</h3>
              <p className="text-xs sm:text-sm text-slate-600 leading-relaxed font-normal">
                {pillar.body}
              </p>
            </div>
          ))}
        </div>

        {/* Compliance & Standards Footer Note */}
        <div className="mt-12 p-4 rounded-xl bg-white border border-slate-200 flex flex-wrap items-center justify-center gap-6 text-xs text-slate-600 shadow-sm">
          <div className="flex items-center gap-2">
            <Lock className="w-4 h-4 text-emerald-600" />
            <span>End-to-End Cryptographic Encryption (AES-256)</span>
          </div>
          <span className="text-slate-300">•</span>
          <div className="flex items-center gap-2">
            <ShieldCheck className="w-4 h-4 text-blue-600" />
            <span>HIPAA Compliant Ingestion Pipelines</span>
          </div>
          <span className="text-slate-300">•</span>
          <div className="flex items-center gap-2">
            <Award className="w-4 h-4 text-amber-600" />
            <span>SOC-2 Type II Certified Cloud Telemetry</span>
          </div>
        </div>
      </div>
    </section>
  );
}
